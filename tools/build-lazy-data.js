// Generate country/function chunks from canonical editor-owned data.
// Run after editing data; --check detects stale output before publishing.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const crypto = require('node:crypto');
const root = path.resolve(__dirname, '..');
const check = process.argv.includes('--check');
const manifest = { prayers:{}, hymns:{}, churches:{}, special:{}, missal:{}, daily:{} };
const generated = '// Generated by tools/build-lazy-data.js. Do not edit.\n';
function output(file, source) {
  const full = path.join(root, 'JS file', file);
  if (check) {
    if (!fs.existsSync(full) || fs.readFileSync(full, 'utf8') !== source) throw Error('Stale lazy data: '+file);
  } else { fs.mkdirSync(path.dirname(full), {recursive:true}); fs.writeFileSync(full, source); }
  return full;
}
function asset(full) {
  return path.relative(path.join(root, 'JS file'), full).replaceAll('\\','/')+'?v='+crypto.createHash('sha256').update(fs.readFileSync(full)).digest('hex').slice(0,12);
}
function evaluate(file) {
  const sandbox = {};
  vm.runInNewContext(fs.readFileSync(path.join(root,'JS file',file),'utf8'), sandbox, {filename:file});
  return sandbox;
}
for (const country of fs.readdirSync(path.join(root,'JS file/countries'), {withFileTypes:true}).filter(d=>d.isDirectory())) {
  for (const file of fs.readdirSync(path.join(root,'JS file/countries',country.name))) {
    const kind = ['prayers','hymns','churches'].find(kind=>file.endsWith('_'+kind+'.js'));
    if (!kind) continue;
    const relative = `countries/${country.name}/${file}`;
    const data = evaluate(relative)['country'+({prayers:'Prayer',hymns:'Hymn',churches:'Church'}[kind])+'Data'] || {};
    for (const [code, module] of Object.entries(data)) {
      manifest[kind][code] = asset(path.join(root,'JS file',relative));
      for (const alias of module.jurisdictions || []) manifest[kind][alias] = manifest[kind][code];
    }
  }
}
const prayerSource = fs.readFileSync(path.join(root,'JS file/countries/korea/korea_prayers.js'),'utf8');
const suffix = prayerSource.slice(prayerSource.indexOf("  const order = ['KR'"));
if (!suffix.includes('global.ordoPrayerDataApi = prayerDataApi;')) throw Error('Prayer API source boundary changed');
output('prayer_data_api.js', generated+'(function(global) {\n  global.countryPrayerData = global.countryPrayerData || {};\n'+suffix);
const special = evaluate('country_special_liturgies_v29.js').countrySpecialLiturgies;
output('lazy/special-common.js', generated+'globalThis.countrySpecialLiturgies = '+JSON.stringify({schemaVersion:special.schemaVersion, universal:special.universal, countries:{}},null,2)+';\n');
for (const [code, profile] of Object.entries(special.countries)) {
  const full = output('lazy/special-'+code+'.js',generated+'globalThis.countrySpecialLiturgies.countries['+JSON.stringify(code)+'] = '+JSON.stringify(profile,null,2)+';\n');
  manifest.special[code] = asset(full);
}
const missal = evaluate('local_missal_prayer_data.js').localMissalPrayerData;
for (const [lang, data] of Object.entries(missal.languages)) {
  const full = output('lazy/missal-'+lang+'.js', generated+'globalThis.localMissalPrayerData = globalThis.localMissalPrayerData || '+JSON.stringify({...missal,languages:{}})+';\n'+'globalThis.localMissalPrayerData.languages['+JSON.stringify(lang)+'] = '+JSON.stringify(data,null,2)+';\n');
  manifest.missal[lang] = asset(full);
}
manifest.daily.TW = asset(path.join(root,'JS file/countries/taiwan/taiwan_daily_mass_data.js'));
output('lazy_data_manifest.js',generated+'globalThis.ordoLazyDataManifest = '+JSON.stringify(manifest,null,2)+';\n');
console.log(check ? 'Lazy data chunks and manifest are current.' : 'Built country/function lazy data chunks and manifest.');
