// Keep editable source and published runtime in sync without renaming globals
// used by inline handlers, the daily collector, and editor previews.
const fs = require('node:fs');
const path = require('node:path');
const { minify } = require('terser');
const root = path.resolve(__dirname, '..');
const release = require('./app-release');
const source = release.source;
const dependencies = ['JS file/preface_matching.js', 'JS file/ordinary_source_repairs.js', 'JS file/ordinary_alignment.js'];
const target = release.runtime;
(async () => {
  const repairData = 'tools/fixtures/eucharistic-prayer-three-recovery.json';
  const repairText = 'globalThis.ordoOrdinaryRecoveryData=' + JSON.stringify(JSON.parse(fs.readFileSync(path.join(root, repairData), 'utf8')).languages) + ';';
  const germanData = 'tools/fixtures/german-fourth-preface.json';
  const inputs = { [repairData]: repairText, [germanData]: 'globalThis.ordoGermanFourthPreface=' + JSON.stringify(JSON.parse(fs.readFileSync(path.join(root,germanData),'utf8')).text) + ';', ...Object.fromEntries([...dependencies, source].map(file => [file, fs.readFileSync(path.join(root, file), 'utf8')])) };
  const original = Object.values(inputs).join('\n');
  const result = await minify(inputs, { compress: false, mangle: false, format: { comments: false, ascii_only: false } });
  const output = '// Generated by npm run app:build from ' + Object.keys(inputs).join(' + ') + '.\n' + result.code + '\n';
  if (process.argv.includes('--check')) {
    const existing = fs.readFileSync(path.join(root, target), 'utf8').replace(/\r\n/g, '\n');
    if (existing !== output) throw Error('Published app runtime is stale; run npm run app:build.');
  } else fs.writeFileSync(path.join(root, target), output);
  console.log(JSON.stringify({ sourceBytes: Buffer.byteLength(original), runtimeBytes: Buffer.byteLength(output), savedPercent: +(100 * (1 - Buffer.byteLength(output) / Buffer.byteLength(original))).toFixed(1) }));
})().catch(error => { console.error(error); process.exitCode = 1; });
