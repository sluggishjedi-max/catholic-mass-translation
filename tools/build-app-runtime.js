// Keep editable source and published runtime in sync without renaming globals
// used by inline handlers, the daily collector, and editor previews.
const fs = require('node:fs');
const path = require('node:path');
const { minify } = require('terser');
const root = path.resolve(__dirname, '..');
const source = 'JS file/app_v31_1.js';
const target = 'JS file/app_v31_1.min.js';
(async () => {
  const original = fs.readFileSync(path.join(root, source), 'utf8');
  const result = await minify(original, { compress: false, mangle: false, format: { comments: false, ascii_only: false } });
  const output = '// Generated by npm run app:build from ' + source + '.\n' + result.code + '\n';
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(path.join(root, target), 'utf8') !== output) throw Error('Published app runtime is stale; run npm run app:build.');
  } else fs.writeFileSync(path.join(root, target), output);
  console.log(JSON.stringify({ sourceBytes: Buffer.byteLength(original), runtimeBytes: Buffer.byteLength(output), savedPercent: +(100 * (1 - Buffer.byteLength(output) / Buffer.byteLength(original))).toFixed(1) }));
})().catch(error => { console.error(error); process.exitCode = 1; });
