const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const input = path.join(root, 'tmp', 'pdfs', 'korean-ordinary-weeks-cbck-proofread.json');
const output = path.join(root, 'JS file', 'korean_temporal_data.js');

function cleanText(value) {
  return String(value || '')
    .split(/이전 오늘 목록|매일미사\s*©/)[0]
    .replace(/천주로서영원히/g, '천주로서 영원히')
    .replace(/성자우리/g, '성자 우리')
    .replace(/[ \t]+\n/g, '\n')
    .trim();
}

function cleanValue(value) {
  if (Array.isArray(value)) return value.map(cleanValue).filter(item => item && (typeof item !== 'object' || item.text !== ''));
  if (!value || typeof value !== 'object') return typeof value === 'string' ? cleanText(value) : value;
  const cleaned = {};
  Object.entries(value).forEach(([key, item]) => {
    cleaned[key] = key === 'text' ? cleanText(item) : cleanValue(item);
  });
  return cleaned;
}

const source = JSON.parse(fs.readFileSync(input, 'utf8'));
const data = {};
for (let week = 1; week <= 34; week += 1) {
  const entry = source[String(week)];
  if (!entry || !entry.parsed || !entry.parsed.data) throw new Error(`Missing week ${week}`);
  data[week] = {
    week,
    pdfPage: 932 + week,
    source: '참고자료/미사/전문/한국어.pdf',
    proofreadDate: entry.proofreadDate,
    data: cleanValue(entry.parsed.data)
  };
}

data[34].data.prayer_after = {
  text: '전능하신 하느님, 이 거룩한 제사에서 성체를 모시고 기뻐하오니 저희가 언제나 하느님 곁에 머무르게 하소서.',
  lines: [{ sp: '', text: '전능하신 하느님, 이 거룩한 제사에서 성체를 모시고 기뻐하오니 저희가 언제나 하느님 곁에 머무르게 하소서.' }]
};

const banner = [
  '/*',
  ' * Korean Roman Missal ordinary-week propers, PDF pages 933-966.',
  ' * OCR transcription proofread against the current CBCK Daily Missal text.',
  ' * Generated by tools/build-korean-temporal-data.js.',
  ' */'
].join('\n');
fs.writeFileSync(output, `${banner}\n\nglobalThis.koreanMissalOrdinaryWeekData = ${JSON.stringify(data, null, 2)};\n`, 'utf8');
