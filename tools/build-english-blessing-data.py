"""Extract the solemn blessings from the supplied English Roman Missal PDF."""
import argparse
import json
import re
from pathlib import Path

import pypdfium2

ROOT = Path(__file__).resolve().parents[1]
KEYS = ['advent', 'christmas', 'new_year', 'epiphany', 'passion', 'easter',
        'ascension', 'pentecost', *[f'ordinary_{n}' for n in range(1, 7)],
        'blessed_virgin_mary', 'peter_and_paul', 'apostles', 'all_saints',
        'church_dedication', 'for_the_dead']


def build():
    document = pypdfium2.PdfDocument(str(ROOT / '참고자료/미사/전문/영어.pdf'))
    entries, current, petition = {}, None, []
    for index in range(671, 682):
        for raw in document[index].get_textpage().get_text_range().splitlines():
            line = raw.strip()
            if not line or re.fullmatch(r'\d+|\d+ THE ORDER OF MASS|SOLEMN BLESSINGS(?: \d+)?', line):
                continue
            match = re.match(r'^(\d+)\. (.+)$', line)
            if match:
                number = int(match[1])
                assert 1 <= number <= 20 and not petition, (number, petition)
                current = {'label': match[2], 'pdfPage': index + 1, 'lines': []}
                entries[KEYS[number - 1]] = current
            elif current and line == 'R. Amen.':
                assert petition
                current['lines'].extend([' '.join(petition).replace(' X ', ' ✠ '), 'R. Amen.'])
                petition = []
            elif current and not re.match(r'^II?I?\. ', line):
                petition.append(line)
    assert len(entries) == 20 and not petition
    assert all(len(entry['lines']) in (4, 8) for entry in entries.values())
    data = {'version': '2026-10-15', 'source': {'title': 'The Roman Missal, Third Edition',
            'pdfPages': '672–682', 'printedPages': '674–684'}, 'solemnBlessings': entries}
    return '// Generated by tools/build-english-blessing-data.py from the supplied Missal.\n' + \
        'globalThis.englishBlessingData = ' + json.dumps(data, ensure_ascii=False, indent=2) + ';\n'


if __name__ == '__main__':
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    output = ROOT / 'JS file/english_blessing_data.js'
    content = build()
    if args.check:
        assert output.read_text(encoding='utf-8') == content, 'English blessing data is stale'
    else:
        output.write_text(content, encoding='utf-8')
    print('20 English solemn blessing formularies verified.')
