def lines(text):
    result = []
    for raw in text.strip().splitlines():
        value = raw.strip()
        if not value:
            continue
        if value.startswith('<') and value.endswith('>'):
            result.append({'rubric': value[1:-1]})
        elif value[0] in '╋◎○●':
            result.append({'sp': value[0], 'text': value[1:].strip()})
        else:
            result.append({'sp': '', 'text': value})
    return result


def approved(text, pages, citation=''):
    return {'lines': lines(text), 'citation': citation, 'source': {**SOURCE, 'pdfPages': pages}}


def prayer(text, conclusion=CHRIST):
    text = text.strip() + '\n' + conclusion
    return {'text': text, 'lines': lines(text)}


